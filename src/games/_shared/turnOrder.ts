/**
 * 선(첫 차례) 정하기 — 모든 게임 공용.
 *
 * 자리 순서는 호스트를 맨 앞에 두고 만든다(색·자리 배정이 거기 묶여 있어서).
 * 그런데 그걸 그대로 쓰면 **늘 방장이 선**이 된다. 선은 매판 바뀌는 게 맞다.
 *
 * 그래서 자리 배열은 건드리지 않고 **시작 지점만** 무작위로 고른다.
 * 자리는 그대로고 출발점만 움직이니 도는 방향(시계방향)은 유지된다.
 *
 *   자리: [방장, 수경, 진상, 맹구]
 *   선이 2 번이면 → 진상 → 맹구 → 방장 → 수경 → 진상 …
 */
export function randomStartIndex(count: number): number {
  if (count <= 1) return 0;
  return Math.floor(Math.random() * count);
}
